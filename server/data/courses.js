/* Lessons are written as compact tuples: [title, minutes, type?, preview?]
   type: video | article | quiz | project */
function defineCourse(course) {
  let counter = 0;
  let totalMinutes = 0;
  const curriculum = course.curriculum.map((section, sIndex) => ({
    id: `${course.id}-s${sIndex + 1}`,
    title: section.title,
    lessons: section.lessons.map(([title, minutes, type = 'video', preview = false]) => {
      counter += 1;
      totalMinutes += minutes;
      return { id: `${course.id}-l${counter}`, title, minutes, type, preview };
    }),
  }));
  return {
    ...course,
    curriculum,
    lessons: counter,
    durationMinutes: totalMinutes,
    duration: Math.max(1, Math.round(totalMinutes / 60)),
  };
}

